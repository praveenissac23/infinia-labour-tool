def key(s):
    return "".join(ch for ch in (s or "").upper() if ch.isalnum())


def run():
    db = SessionLocal()
    by = {key(e.emp_no): e for e in db.query(models.Employee).all()}
    done, missing, total = 0, [], 0.0
    for code, days, months in DATA:
        e = by.get(key(code))
        if not e:
            missing.append(code)
            continue
        e.past_not_service = round(days, 2)
        e.past_not_service_note = (f"{SRC}: {months}" if days else "")[:500]
        done += 1
        total += days
    db.commit()
    db.close()
    print(f"Set for {done} people - {total:g} days in all.")
    if missing:
        print("Not found in the app:", ", ".join(missing))


if __name__ == "__main__":
    run()
